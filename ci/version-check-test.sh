#!/bin/bash
# ci/version-check.sh 의 시험 — 스스로 짓는 작은 저장소에서 출시 경우마다 돌려 기대한 종료 코드인지 본다.
#
#   bash ci/version-check-test.sh
#
# 검사 스크립트(태그 꼴 · Latest 와 견주기 · 엔진 비교 · 룰 버전)를 고치면 돌린다. 이 저장소의 역사와 태그는 쓰지 않는다 —
# 임시 폴더에 엔진 버전 줄 · Cargo.lock(작업 공간 크레이트 하나와 외부 의존성 하나) · crates/ · plugins/ 를 지어 커밋과 태그를
# 쌓으며 경우마다 검사를 부른다. 지금 Latest 는 늘 `--prev` · `--prev-name` 으로 준다 — 망과 gh 를 쓰지 않는다. 오늘은
# `--today` 로 못박는다. Git Bash · 리눅스 어디서나 돈다.
#
# 외부 의존성 `dep` 은 **일부러 버전만 올리는 엔진 버전(1.2.1)과 같은 버전**이다 — 버전 문자열을 통째로 가리던 첫 판이 그
# 탓에 버전만 올린 커밋을 '엔진이 바뀌었다' 로 봤다.
#
# 종료 코드: 0 = 모든 경우가 기대대로 · 1 = 하나라도 아니다.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
CHECK="$HERE/version-check.sh"
W=$(mktemp -d)
trap 'cd / && rm -rf "$W"' EXIT
cd "$W" || exit 1
git init -q -b main
git config user.email version-check-test@example.invalid
git config user.name version-check-test
git config commit.gpgsign false
git config tag.gpgsign false
git config core.autocrlf false
git config core.hooksPath "$W/.no-hooks"

TODAY=2026-01-10
pass=0
failed=0
# 지금 Latest — latest <태그> <이름>
LATEST="" LNAME=""
latest() { LATEST=$1; LNAME=$2; }
# expect <ok|fail> <이름> <검사 인자…> — ok 는 종료 0, fail 은 종료 1(정책 위반)을 기대한다. 2(쓰는 법)는 늘 틀린 것이다.
# 지금 Latest 와 오늘을 붙여 부른다(`--no-prev` 를 주면 Latest 없이).
expect() {
    local want=$1 name=$2 out rc args=()
    shift 2
    case " $* " in *" --no-prev "* | *" --prev "*) ;; *) args=(--prev "$LATEST" --prev-name "$LNAME") ;; esac
    # Actions 걸음 안에서 돌면 물려받은 GITHUB_OUTPUT 에 검사가 값을 쓴다 — 시험은 그 파일을 건드리지 않는다.
    out=$(GITHUB_OUTPUT= bash "$CHECK" "$@" "${args[@]}" --today "$TODAY" 2>&1)
    rc=$?
    if { [ "$want" = ok ] && [ $rc = 0 ]; } || { [ "$want" = fail ] && [ $rc = 1 ]; }; then
        pass=$((pass + 1))
        echo "통과  $name"
    else
        failed=$((failed + 1))
        echo "실패  $name — 종료 $rc(기대 $want): $(printf '%s' "$out" | tail -1)"
    fi
}
# expect_out <이름> <기대 줄들(공백으로 이음)> <검사 인자…> — 잡 출력(GITHUB_OUTPUT)이 그 줄들인가.
expect_out() {
    local name=$1 want=$2 gh_out got
    shift 2
    gh_out=$(mktemp)
    GITHUB_OUTPUT="$gh_out" bash "$CHECK" "$@" --prev "$LATEST" --prev-name "$LNAME" --today "$TODAY" >/dev/null 2>&1
    got=$(tr '\n' ' ' <"$gh_out" | sed 's/ $//')
    rm -f "$gh_out"
    if [ "$got" = "$want" ]; then
        pass=$((pass + 1))
        echo "통과  $name"
    else
        failed=$((failed + 1))
        echo "실패  $name — '$got'(기대 '$want')"
    fi
}
setver() {
    printf '[workspace]\nmembers = ["crates/*"]\n\n[workspace.package]\nversion = "%s"\n' "$1" >Cargo.toml
    printf '%s\n' '# This file is automatically @generated by Cargo.' 'version = 4' '' \
        '[[package]]' 'name = "core"' "version = \"$1\"" '' \
        '[[package]]' 'name = "dep"' 'version = "1.2.1"' \
        'source = "registry+https://github.com/rust-lang/crates.io-index"' >Cargo.lock
}
engine_edit() { echo "// $1" >>crates/core/src/lib.rs; }
rules_edit() { echo "# $1" >>plugins/r/plugin.yaml; }
commit() { git add -A && git commit -q -m "$1"; }
etag() { git tag -a "$1" -m "$2"; }

mkdir -p crates/core/src plugins/r
echo "// core" >crates/core/src/lib.rs
echo "id: r" >plugins/r/plugin.yaml
setver 1.0.0
commit "첫 출시"
expect ok   "첫 출시 — 지난 공개본 없이 꼴만" v1.0.0 --rules 2026.01.05 --no-prev
etag v1.0.0 "프로그램 1.0.0 · 룰 2026.01.05"
latest v1.0.0 "프로그램 1.0.0 · 룰 2026.01.05"

# 엔진이 바뀐 출시 — 룰은 그대로.
engine_edit a
setver 1.1.0
commit "엔진 기능"
expect ok   "엔진 출시(태그 전 --rules)" v1.1.0 --rules 2026.01.05
expect ok   "엔진 시험판" v1.1.0-rc.1 --rules 2026.01.05
expect fail "룰이 그대로인 rules 태그" rules-2026.01.06
expect fail "태그가 엔진 버전과 다르다" v1.0.9 --rules 2026.01.05
expect fail "v 도 rules 도 아닌 태그" 1.1.0
expect fail "v 태그에 룰 버전이 없다" v1.1.0
git tag v1.1.0
expect fail "가벼운 v 태그(룰 버전을 적지 못한다)" v1.1.0
git tag -d v1.1.0 >/dev/null
etag v1.1.0-rc.2 "프로그램 1.0.0 · 룰 2026.01.05"
expect fail "태그 메시지의 엔진이 태그와 다르다" v1.1.0-rc.2
git tag -d v1.1.0-rc.2 >/dev/null
etag v1.1.0 "프로그램 1.1.0 · 룰 2026.01.05"
expect ok   "주석 태그 메시지의 룰 버전" v1.1.0
expect fail "--rules 가 태그 메시지와 다르다" v1.1.0 --rules 2026.01.06
latest v1.1.0 "프로그램 1.1.0 · 룰 2026.01.05"

# 룰만 바뀐 출시.
rules_edit a
commit "룰"
expect ok   "룰만 바뀐 출시" rules-2026.01.07
expect_out  "잡 출력 — 지난 공개본 · 그 엔진 · 싣는 엔진 · 룰" \
    "prev=v1.1.0 prev_engine=1.1.0 engine=1.1.0 rules=2026.01.07" rules-2026.01.07
expect ok   "룰 시험판" rules-2026.01.07-rc.1
expect fail "룰 버전이 Latest 보다 높지 않다" rules-2026.01.04
expect ok   "오늘(KST)+1 까지는 받는다" rules-2026.01.11
expect fail "룰 버전의 날이 하루 넘게 늦다" rules-2026.01.12
expect fail "다른 커밋에 이미 있는 태그" v1.1.0
expect fail "--prev 의 이름이 꼴이 아니다" rules-2026.01.07 --prev v1.1.0 --prev-name "v1.1.0"
expect fail "--prev 와 그 이름의 버전이 다르다" rules-2026.01.07 --prev v1.1.0 --prev-name "프로그램 1.0.0 · 룰 2026.01.05"
expect fail "--prev 만 주고 이름이 없다" rules-2026.01.07 --prev v1.1.0 --prev-name ""
git tag rules-2026.01.07
latest rules-2026.01.07 "프로그램 1.1.0 · 룰 2026.01.07"

# 룰 버전 파일 · 잠금 · 개발 키 서명만 바뀐 것은 룰이 바뀐 것이 아니다(2026-11-21 부터 저장소에 두지 않는 자리).
mkdir -p plugins
echo "2026.01.08" >plugins/RULES-VERSION
echo "{}" >plugins/versions.lock.json
echo "# remedy plugin manifest v1" >plugins/r/MANIFEST
echo "untrusted comment: x" >plugins/r/MANIFEST.minisig
commit "옛 자리만"
expect fail "룰 버전 파일 · 잠금 · 서명만 바뀐 rules 태그" rules-2026.01.08
git rm -q plugins/RULES-VERSION plugins/versions.lock.json plugins/r/MANIFEST plugins/r/MANIFEST.minisig
commit "옛 자리 지움"

# main 의 엔진이 공개본보다 앞서 있어도 룰 출시가 선다 — 싣는 엔진은 Latest 의 것이다.
engine_edit b
setver 1.2.0
rules_edit b
commit "엔진도 룰도"
expect ok   "엔진이 앞선 main 의 rules 태그" rules-2026.01.08
expect_out  "그때 싣는 엔진은 Latest 의 것" \
    "prev=rules-2026.01.07 prev_engine=1.1.0 engine=1.1.0 rules=2026.01.08" rules-2026.01.08
expect ok   "같은 커밋의 v 태그 — Latest 가 싣는 엔진(v1.1.0)과 견준다" v1.2.0 --rules 2026.01.08
expect fail "v 태그의 룰 버전이 Latest 보다 높지 않다" v1.2.0 --rules 2026.01.07
git tag rules-2026.01.08
latest rules-2026.01.08 "프로그램 1.1.0 · 룰 2026.01.08"
expect ok   "룰 그대로면 룰 버전도 그대로" v1.2.0 --rules 2026.01.08
expect fail "룰이 그대로인데 룰 버전을 올렸다" v1.2.0 --rules 2026.01.09
# 엔진을 고친 채 버전을 Latest 가 싣는 엔진(1.1.0)보다 낮췄다 — 이 커밋은 시험 뒤 버린다.
setver 1.0.5
commit "버전 낮춤"
expect fail "엔진 버전을 낮췄다" v1.0.5 --rules 2026.01.08
git reset -q --hard HEAD^
etag v1.2.0 "프로그램 1.2.0 · 룰 2026.01.08"
latest v1.2.0 "프로그램 1.2.0 · 룰 2026.01.08"
MAIN_AT_120=$(git rev-parse HEAD)

# 버전만 올렸다 — Cargo.lock 에 새 버전과 같은 외부 의존성이 있어도 엔진은 그대로다.
setver 1.2.1
commit "버전만"
expect fail "버전만 올린 v 태그(같은 버전의 외부 의존성)" v1.2.1 --rules 2026.01.08
git reset -q --hard HEAD^

# Latest 가 조상이 아닌 커밋 — 새 출시가 Latest 의 룰을 빠뜨린다.
git checkout -q -b side rules-2026.01.07
rules_edit s
commit "곁가지 룰"
expect fail "Latest 가 조상이 아니다" rules-2026.01.09
git checkout -q main

# 긴급 가지를 병합 커밋으로 되돌린 뒤 — 첫 부모만 보던 옛 판은 병합으로 들어온 태그를 건너뛰어 낮은 룰 버전이 지났다.
git checkout -q -b emergency "$MAIN_AT_120"
# 긴급 룰은 새 폴더 — 아래 병합이 main 의 룰 고침과 부딪히지 않게.
mkdir -p plugins/e
echo "id: e" >plugins/e/plugin.yaml
commit "긴급 룰"
git tag rules-2026.01.09
latest rules-2026.01.09 "프로그램 1.2.0 · 룰 2026.01.09"
git checkout -q main
rules_edit m
commit "main 의 룰"
expect fail "긴급 출시를 품지 않은 main — Latest 가 조상이 아니다" rules-2026.01.10
git merge -q --no-ff -m "긴급 가지 되돌림" emergency
expect fail "병합된 긴급 태그보다 낮은 룰 버전" rules-2026.01.08.2
expect ok   "병합 뒤 더 높은 룰 버전" rules-2026.01.10

echo "--- 통과 $pass · 실패 $failed"
[ "$failed" = 0 ]
