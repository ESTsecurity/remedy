#!/bin/bash
# ci/version-check.sh 의 시험 — 스스로 짓는 작은 저장소에서 출시 경우마다 돌려 기대한 종료 코드인지 본다.
#
#   bash ci/version-check-test.sh
#
# 검사 스크립트(태그 꼴 · 지난 공개본 고르기 · 엔진 비교 · 룰 버전)를 고치면 돌린다. 이 저장소의 역사와 태그는 쓰지 않는다 —
# 임시 폴더에 엔진 버전 줄 · Cargo.lock(작업 공간 크레이트 하나와 외부 의존성 하나) · crates/ · plugins/ 를 지어 커밋과 태그를
# 쌓으며 경우마다 검사를 부른다. 망을 쓰지 않는다. Git Bash · 리눅스 어디서나 돈다.
#
# 외부 의존성 `dep` 은 **일부러 다음 엔진 버전(1.1.1)과 같은 버전**이다 — 버전 문자열을 통째로 가리던 첫 판이 그 탓에
# 버전만 올린 커밋을 '엔진이 바뀌었다' 로 봤다(경우 g).
#
# 종료 코드: 0 = 모든 경우가 기대대로 · 1 = 하나라도 아니다.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
CHECK="$HERE/version-check.sh"
W=$(mktemp -d)
trap 'cd / && rm -rf "$W"' EXIT
cd "$W" || exit 1
git init -q -b main
git config user.email version-check-test@example.invalid
git config user.name version-check-test
git config commit.gpgsign false
git config tag.gpgsign false
git config core.autocrlf false
git config core.hooksPath "$W/.no-hooks"

pass=0
failed=0
# expect <ok|fail> <이름> <검사 인자…> — ok 는 종료 0, fail 은 종료 1(정책 위반)을 기대한다. 2(쓰는 법)는 늘 틀린 것이다.
expect() {
    local want=$1 name=$2 out rc
    shift 2
    # Actions 걸음 안에서 돌면 물려받은 GITHUB_OUTPUT 에 검사가 `prev=` 를 쓴다 — 시험은 그 파일을 건드리지 않는다.
    out=$(GITHUB_OUTPUT= bash "$CHECK" "$@" 2>&1)
    rc=$?
    if { [ "$want" = ok ] && [ $rc = 0 ]; } || { [ "$want" = fail ] && [ $rc = 1 ]; }; then
        pass=$((pass + 1))
        echo "통과  $name"
    else
        failed=$((failed + 1))
        echo "실패  $name — 종료 $rc(기대 $want): $(printf '%s' "$out" | tail -1)"
    fi
}
setver() {
    printf '[workspace]\nmembers = ["crates/*"]\n\n[workspace.package]\nversion = "%s"\n' "$1" >Cargo.toml
    printf '%s\n' '# This file is automatically @generated by Cargo.' 'version = 4' '' \
        '[[package]]' 'name = "core"' "version = \"$1\"" '' \
        '[[package]]' 'name = "dep"' 'version = "1.1.1"' \
        'source = "registry+https://github.com/rust-lang/crates.io-index"' >Cargo.lock
}
rules() { printf '%s\n' "$1" >plugins/RULES-VERSION; }
engine_edit() { echo "// $1" >>crates/core/src/lib.rs; }
rules_edit() { echo "# $1" >>plugins/r/plugin.yaml; }
commit() { git add -A && git commit -q -m "$1"; }

mkdir -p crates/core/src plugins/r
echo "// core" >crates/core/src/lib.rs
echo "id: r" >plugins/r/plugin.yaml
setver 1.0.0
rules 2026.01.05
commit "첫 출시"
expect ok   "첫 출시 — 지난 공개본이 없으면 꼴만 본다" v1.0.0
git tag v1.0.0

# 엔진이 바뀐 출시 — 룰은 그대로.
engine_edit a
setver 1.1.0
commit "엔진 기능"
expect ok   "엔진 출시" v1.1.0
expect ok   "엔진 시험판" v1.1.0-rc.1
expect fail "엔진이 바뀐 커밋의 rules 태그" rules-2026.01.05
expect fail "태그가 엔진 버전과 다르다" v1.0.9
expect fail "v 도 rules 도 아닌 태그" 1.1.0
git tag v1.1.0-rc.1
expect ok   "시험판 커밋에 민 정식 태그" v1.1.0
git tag v1.1.0
expect ok   "정식 태그의 제 커밋에서 다시 돌린다" v1.1.0 --ref v1.1.0

# 룰만 바뀐 출시.
rules_edit a
rules 2026.01.07
commit "룰"
expect ok   "룰만 바뀐 출시" rules-2026.01.07
# 잡 안에서는 견준 지난 공개본을 `prev=<태그>` 로 낸다 — 배포 워크플로가 룰만 바뀐 출시의 실행 파일을 거기서 받는다.
# expect_prev <이름> <기대 태그> <검사 인자…>
expect_prev() {
    local name=$1 want=$2 gh_out got
    shift 2
    gh_out=$(mktemp)
    GITHUB_OUTPUT="$gh_out" bash "$CHECK" "$@" >/dev/null 2>&1
    got=$(cat "$gh_out")
    rm -f "$gh_out"
    if [ "$got" = "prev=$want" ]; then
        pass=$((pass + 1))
        echo "통과  $name"
    else
        failed=$((failed + 1))
        echo "실패  $name — '$got'(기대 prev=$want)"
    fi
}
expect_prev "지난 공개본을 잡 출력으로 낸다" v1.1.0 rules-2026.01.07
# 사선이 든 이름(태그 룰셋 밖 — Owner 가 아니어도 만든다)은 더 가까워도 지난 공개본으로 고르지 않는다.
git tag v9/x
expect_prev "사선이 든 태그는 지난 공개본으로 고르지 않는다" v1.1.0 rules-2026.01.07
git tag -d v9/x >/dev/null
expect ok   "룰 시험판" rules-2026.01.07-rc.1
expect fail "다른 커밋에 이미 있는 태그" v1.1.0
git tag rules-2026.01.07

# 엔진과 룰이 바뀌었는데 룰 버전을 올리지 않았다 — 이 커밋은 시험 뒤 버린다.
engine_edit e
rules_edit e
setver 1.1.9
commit "룰 버전을 잊었다"
expect fail "룰이 바뀌었는데 룰 버전이 그대로" v1.1.9
git reset -q --hard HEAD^

# 같은 날 둘째 룰 출시.
rules_edit b
rules 2026.01.07.2
commit "룰 둘째"
expect ok   "같은 날 둘째 룰 버전" rules-2026.01.07.2
git tag rules-2026.01.07.2

# 버전만 올렸다 — Cargo.lock 에 새 버전과 같은 외부 의존성이 있어도 엔진은 그대로다.
setver 1.1.1
commit "버전만"
expect fail "버전만 올린 v 태그(같은 버전의 외부 의존성)" v1.1.1
# 그 커밋에 룰을 더해 rules 태그로 내도 멈춘다 — 룰만 바뀐 출시는 지난 공개본의 실행 파일(옛 버전)을 그대로 싣는다.
# 이 커밋은 시험 뒤 버린다.
rules_edit v
rules 2026.01.07.3
commit "버전만 올린 채 룰"
expect fail "엔진 버전만 올린 커밋의 rules 태그" rules-2026.01.07.3
git reset -q --hard HEAD^
engine_edit f
commit "엔진 고침"
expect ok   "엔진 고침 — 룰 그대로면 룰 버전도 그대로" v1.1.1
rules 2026.01.08
commit "룰 없이 룰 버전만"
expect fail "룰이 그대로인데 룰 버전을 올렸다" v1.1.1
rules 2026.01.07.2
commit "룰 버전 되돌림"
git tag v1.1.1

# 엔진이 바뀐 채 rules 태그 · 낮춘 엔진 버전 · 틀린 꼴 · 룰 버전 파일 없음.
engine_edit k
rules_edit k
rules 2026.01.09
commit "엔진도 룰도"
expect fail "엔진이 바뀌었는데 rules 태그" rules-2026.01.09
setver 1.0.5
commit "버전 낮춤"
expect fail "엔진 버전을 낮췄다" v1.0.5
rules 2026.1.9
commit "틀린 꼴"
expect fail "룰 버전의 꼴이 틀렸다" v1.0.5
git rm -q plugins/RULES-VERSION
commit "파일 없음"
expect fail "룰 버전 파일이 없다" v1.0.5

# 시험판 태그는 지난 공개본으로 세지 않는다 — 정식 태그만.
git checkout -q -b side v1.1.0
git tag v1.1.2-rc.9
engine_edit m
setver 1.1.2
commit "곁가지"
expect ok   "시험판 태그는 지난 공개본이 아니다" v1.1.2

echo "--- 통과 $pass · 실패 $failed"
[ "$failed" = 0 ]
